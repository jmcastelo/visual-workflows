"""The UPF header reader, on the three layouts pw.x reads. The headers below
follow real files' (ONCVPSP/PseudoDojo UPF 2, FHI converted to UPF 2, the
schema form, UPF 1 from QE's library), cut to what the reader needs."""

import pytest

from fakes import upf
from visual_workflows.yambopy_ext.qepy.upf import HEADER_BYTES, UpfError, read_upf_header

UPF1 = """<PP_INFO>
 Generated by hand
</PP_INFO>
<PP_HEADER>
   0                   Version Number
  Si                   Element
   NC                  Norm - Conserving pseudopotential
    F                  Nonlinear Core Correction
 SLA  PZ   NOGX NOGC   PZ   Exchange-Correlation functional
    4.00000000000      Z valence
   -7.47480832270      Total energy
    0.0000000    0.0000000 Suggested cutoff for wfc and rho
    1                  Max angular momentum component
  431                  Number of points in mesh
    2    2             Number of Wavefunctions, Number of Projectors
 Wavefunctions         nl  l   occ
                       3S  0  2.00
                       3P  1  2.00
</PP_HEADER>
<PP_MESH>
</PP_MESH>
<PP_NONLOCAL>
</PP_NONLOCAL>
"""

SCHEMA = """<qe_pp:pseudo xmlns:qe_pp="http://www.quantum-espresso.org/ns/qes/qes_pp-1.0">
<pp_header>
  <element>Ga</element>
  <z_valence>13.0</z_valence>
  <type>PAW</type>
  <functional>PBE</functional>
  <relativistic>scalar</relativistic>
  <is_ultrasoft>true</is_ultrasoft>
  <is_paw>true</is_paw>
  <has_so>false</has_so>
  <core_correction>true</core_correction>
  <wfc_cutoff>33.4</wfc_cutoff>
  <rho_cutoff>140.0</rho_cutoff>
</pp_header>
</qe_pp:pseudo>
"""


def test_upf2():
    h = read_upf_header(upf("Mo", 14.0, has_so=True))
    assert (h.element, h.pseudo_type, h.z_valence, h.has_so, h.relativistic, h.version) == \
        ("Mo", "NC", 14.0, True, "full", 2)
    assert h.norm_conserving and h.functional == "PBE" and h.wfc_cutoff == 0.0
    paw = read_upf_header(upf("As", 5.0, "PAW", functional="SLA PW PBX PBC", wfc_cutoff=19.9))
    assert paw.is_paw and paw.is_ultrasoft and not paw.norm_conserving and paw.wfc_cutoff == 19.9
    assert not read_upf_header(upf("Au", 11.0, "USPP")).norm_conserving


def test_schema_form():
    h = read_upf_header(SCHEMA)
    assert (h.element, h.pseudo_type, h.z_valence, h.is_paw, h.core_correction, h.rho_cutoff) == \
        ("Ga", "PAW", 13.0, True, True, 140.0)


def test_upf1():
    h = read_upf_header(UPF1)
    assert (h.element, h.pseudo_type, h.z_valence, h.functional, h.version) == \
        ("Si", "NC", 4.0, "SLA PZ NOGX NOGC", 1)
    assert h.has_so is False                          # read past PP_NONLOCAL: no PP_ADDINFO
    assert read_upf_header(UPF1 + "<PP_ADDINFO>\n</PP_ADDINFO>\n").has_so is True
    # Only the start read (a remote file): spin–orbit unknown
    assert read_upf_header(UPF1.split("<PP_NONLOCAL>")[0]).has_so is None
    assert read_upf_header(UPF1.replace("   NC  ", "   US  ")).is_ultrasoft


@pytest.mark.parametrize("text, message", [
    ("<UPF version='2.0.1'>\n<PP_INFO>\n", "no PP_HEADER"),
    ("not a pseudopotential", "no PP_HEADER"),
    (UPF1.replace("   NC  ", "   XX  "), "unknown pseudo type"),
    ('<PP_HEADER element="Si" pseudo_type="NC"/>', "without z_valence"),
])
def test_errors(text, message):
    with pytest.raises(UpfError, match=message):
        read_upf_header(text)


def test_header_bytes_cover_a_long_pp_info():
    # PseudoDojo files carry the generator's whole input before the header
    long_info = upf().replace("Generated for tests", "x" * 30000)
    assert len(long_info) < HEADER_BYTES and read_upf_header(long_info[:HEADER_BYTES]).element == "Si"
