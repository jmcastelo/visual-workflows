"""
yambo_variables.py
==================
The names yambo reads from its input, per version: runlevels, logical flags
and variables (blocks included), spelt as yambo spells them, from the tags
``5.1.1``, ``5.2.4``, ``5.3.0`` and ``5.4-beta`` (as 5.4).

yambo ignores any other name without a message (``mod_it_tools.F``), and finds
a variable's unit only on a line where the name is spelt as here
(``OUTPUT_unit_conversion.F``): both are worth a warning.

How the lists were made, for adding a version: the names of every
``call it(...)`` in ``src/interface/INIT_load.F``, ``INIT_QP_ctl_load.F``,
``INIT_RT_ctl_load.F`` and ``INIT_C_driver_runlevels.F`` (``'r'``: runlevel,
``'f'``: flag, else a variable); the runlevels of the C driver
(``yambo_string`` in ``src/driver/options_yambo.c``, ``options_projects.c``,
``options_control.c``); the generated families: response-function names
(the 6-character stems of ``Xload``'s ``nms`` with ``Xx``, ``Xs``, ``Xd``,
``Xp``, ``Xm``), the parallel variables of each section of ``mod_parallel.F``
(``_CPU``, ``_ROLEs``, ``_nCPU_LinAlg_INV``, ``_nCPU_LinAlg_DIAGO``), the QP
and real-time controls (prefixes ``X``, ``K``, ``G``, spins ``''``, ``_up``,
``_dn``); the blocks read with ``PARSER_array(VAR=...)`` and the names read
with ``call parser('...')`` anywhere in ``src/``. Fields of real-time runs
(``Field1_Freq``...) as a pattern. Checked against the 38 yambo inputs of
YamboPy's references and tutorials: the only names missing are Yambo 4's.

ypp's names (``YPP_NAMES``) come from its loader ``ypp/interface/INIT_load_ypp.F``
(every name literal), the QP controls it loads (yambo's, prefix ``G``), the
names read with ``parser``/``PARSER_array`` in ``ypp/``, and its options'
runlevels (``options_ypp.c``).
The command-line options of yambo, ypp and p2y per version (``YAMBO_OPTIONS``)
come from the option tables ``src/driver/options_*.c``: an option whose
``yambo_string`` is a runlevel of that executable makes it write its input
file and exit instead of running (``INIT_read_command_line.F``), except for
the job name, folders, walltime and memory.

Meant for ``yambopy.io``.
"""

