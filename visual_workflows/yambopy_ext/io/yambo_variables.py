def _major_minor(version):
    """(major, minor) of a version given as '5.2.4', '5.2' or (5, 2, 4)."""
    parts = version.split('.') if isinstance(version, str) else list(version)
    return tuple(int(x) for x in parts[:2])


def _version_key(versions, version):
    known = sorted(versions, key=lambda v: tuple(int(x) for x in v.split('.')))
    if version is None:
        return known[-1]
    below = [v for v in known if tuple(int(x) for x in v.split('.'))[:2] <= _major_minor(version)]
    return below[-1] if below else known[0]


def yambo_options(executable='yambo', version=None):
    """
    The command-line options of yambo, ypp or p2y for a version.

    Returns
    -------
    list of dict
        'short' (one letter or ''), 'long' (without the dash), 'arg' ('int',
        'char', 'float' or '': no value), 'kind' ('job': fine in a job;
        'editing': the input file is written and nothing runs; 'exit': prints
        something and exits).
    """
    return [dict(o) for o in YAMBO_OPTIONS[_version_key(YAMBO_OPTIONS, version)][executable]]


def yambo_names(version=None):
    """
    The names yambo reads, for a version.

    Parameters
    ----------
    version : tuple of int, optional
        (major, minor), e.g. (5, 3); the closest known version at or below it
        (or the oldest known). None: the newest known.

    Returns
    -------
    dict
        'runlevels', 'flags', 'variables': sets of names as yambo spells them;
        'patterns': regular expressions of generated names; 'sections': the
        parallel sections; 'units': {name: kind of unit} ('E_unit' energies,
        'G_unit' G vectors, 'T_unit' times...).
    """
    names = YAMBO_NAMES[_version_key(YAMBO_NAMES, version)]
    return {key: (dict(value) if key == 'units' else
                  list(value) if key in ('patterns', 'sections') else set(value))
            for key, value in names.items()}


def ypp_names(version=None):
    """The names ypp reads, for a version (as :func:`yambo_names`)."""
    return {k: list(v) if isinstance(v, list) else dict(v)
            for k, v in YPP_NAMES[_version_key(YPP_NAMES, version)].items()}


def canonical_name(name, version=None, executable='yambo'):
    """
    The name as yambo (or ypp) spells it ('bsengexx' -> 'BSENGexx'), or None
    if it does not read it.
    """
    names = ypp_names(version) if executable == 'ypp' else yambo_names(version)
    lower = name.lower()
    for key in ('runlevels', 'flags', 'variables'):
        for known in names[key]:
            if known.lower() == lower:
                return known
    if any(re.fullmatch(pattern, name, re.I) for pattern in names['patterns']):
        return name
    return None
