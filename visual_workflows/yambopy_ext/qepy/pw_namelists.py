def pw_namelists(version=None):
    """
    The accepted variables of each namelist for a QE version.

    Parameters
    ----------
    version : tuple of int, optional
        (major, minor), e.g. (7, 5); the closest known version at or below it
        (or the oldest known). None: the newest known.

    Returns
    -------
    dict
        {namelist: set of names}, namelists lowercase without '&'.
    """
    known = sorted(PW_NAMELISTS, key=lambda v: tuple(int(x) for x in v.split('.')))
    chosen = known[-1]
    if version is not None:
        below = [v for v in known if tuple(int(x) for x in v.split('.'))[:2] <= tuple(version)[:2]]
        chosen = below[-1] if below else known[0]
    return {name: set(names) for name, names in PW_NAMELISTS[chosen].items()}
